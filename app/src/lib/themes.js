const DEFAULT_THEME = {
  mode: DEFAULT_MODE,
  color: DEFAULT_COLOR,
};

function resolveColorId(colorId, mode) {
  const palettes = THEME_PALETTES[mode] || THEME_PALETTES.dark;
  if (palettes[colorId]) return colorId;
  return DEFAULT_COLOR;
}

function migrateLegacyTheme(raw) {
  if (raw?.mode && raw?.color) return null;
  const legacyId = raw?.preset;
  if (!legacyId) return null;
  const color =
    LEGACY_PRESET_TO_COLOR[legacyId] ||
    (THEME_PALETTES.dark[legacyId] ? legacyId : DEFAULT_COLOR);
  return { mode: DEFAULT_MODE, color };
}

export function getThemePalette(mode, color) {
  const m = mode === 'light' ? 'light' : 'dark';
  const c = resolveColorId(color, m);
  const palette = THEME_PALETTES[m][c];
  return {
    id: c,
    name: THEME_COLOR_LABELS[c],
    mode: m,
    ...palette,
  };
}

export function normalizeThemeConfig(raw) {
  const migrated = migrateLegacyTheme(raw);
  const mode = raw?.mode === 'light' || migrated?.mode === 'light' ? 'light' : 'dark';
  const color = resolveColorId(raw?.color || migrated?.color, mode);

  return {
    mode,
    color,
    logoDataUrl: raw?.logoDataUrl || null,
    backgroundImageDataUrl: raw?.backgroundImageDataUrl || null,
  };
}

export function resolveTheme(themeConfig) {
  const normalized = normalizeThemeConfig(themeConfig);
  const palette = getThemePalette(normalized.mode, normalized.color);
  const isLight = normalized.mode === 'light';

  return {
    ...palette,
    ...normalized,
    cssVars: {
      '--bg-from': palette.bgFrom,
      '--bg-via': palette.bgVia,
      '--bg-to': palette.bgTo,
      '--accent': palette.accent,
      '--accent-soft': palette.accentSoft,
      '--liquid': palette.liquid,
      '--liquid-glow': palette.liquidGlow,
      '--text': palette.text,
      '--text-muted': palette.textMuted,
      '--thermo-glow': palette.thermoGlow,
      '--particle': palette.particle,
      '--card-bg': palette.cardBg,
      '--card-border': palette.cardBorder,
      '--card-highlight': palette.cardHighlight,
      '--card-shadow': palette.cardShadow,
      '--progress-track': palette.progressTrack,
      '--title-shadow': palette.titleShadow,
      '--haze-opacity': isLight ? '0.16' : '0.85',
      '--thermo-atmosphere-opacity': isLight ? '0.12' : '0.75',
      '--bokeh-peak-opacity': isLight ? '0.1' : '0.35',
      '--particle-peak-opacity': isLight ? '0.28' : '0.7',
      '--vignette-edge': isLight ? 'rgba(0, 0, 0, 0.06)' : 'rgba(0, 0, 0, 0.65)',
      '--scale-label': isLight ? palette.textMuted : 'rgba(240, 215, 140, 0.88)',
      '--scale-label-major': isLight ? palette.text : 'rgba(253, 230, 138, 0.95)',
      '--scale-label-current': isLight ? palette.text : '#fde68a',
      '--scale-label-current-bg': isLight
        ? 'rgba(255, 255, 255, 0.96)'
        : 'rgba(8, 10, 18, 0.92)',
      '--scale-label-current-shadow': isLight
        ? '0 1px 4px rgba(15, 23, 42, 0.12)'
        : '0 0 14px rgba(253, 230, 138, 0.85)',
      '--scale-tick': isLight ? palette.accent : '#d4a853',
      '--scale-tick-shadow': isLight
        ? 'none'
        : '0 0 5px rgba(212, 168, 83, 0.45)',
      '--scale-tick-current': isLight ? palette.accent : '#fde68a',
      '--scale-tick-current-shadow': isLight
        ? 'none'
        : '0 0 10px rgba(253, 230, 138, 0.9)',
    },
  };
}

